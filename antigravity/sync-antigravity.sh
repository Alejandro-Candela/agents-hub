#!/usr/bin/env bash
# Generate Antigravity subagents (~/.gemini/config/agents/<name>.md) from agents/*.md.
#
# Generated, not symlinked: Antigravity wants `tools:` as a YAML list of its own
# tool names, and an unknown tool name can hang the subagent (documented known
# issue), so Claude Code's tool names are mapped explicitly below. A Claude agent
# with no `tools:` line gets every mapped tool, matching Claude's "all tools".
# Agents are subagent-only (`mainAgent: false`).
#
# Re-run after adding or editing an agent. Commands and skills already reach
# Antigravity through the global_workflows and skills symlinks (see README).

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$HOME/.gemini/config/agents"
MARKER="Generated by agents-hub/antigravity/sync-antigravity.sh"

map_tool() {
  case "$1" in
    Read)  echo view_file; echo list_dir ;;
    Grep)  echo grep_search ;;
    Glob)  echo find_by_name ;;
    Bash)  echo run_command ;;
    Edit)  echo replace_file_content; echo multi_replace_file_content ;;
    Write) echo write_to_file ;;
  esac
}

mkdir -p "$OUT"
{ grep -l "$MARKER" "$OUT/"*.md 2>/dev/null || true; } | xargs rm -f

for src in "$REPO"/agents/*.md; do
  name=$(basename "$src" .md)
  frontmatter=$(awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {exit} in_fm' "$src")
  description=$(echo "$frontmatter" | grep -m1 '^description:' || true)
  tools=$(echo "$frontmatter" | sed -n 's/^tools:[[:space:]]*//p')
  [ -z "$tools" ] && tools="Read, Grep, Glob, Bash, Edit, Write"

  {
    echo "---"
    echo "name: $name"
    echo "$description"
    echo "tools:"
    for t in $(echo "$tools" | tr ',' ' '); do map_tool "$t"; done | awk '!seen[$0]++ {print "  - " $0}'
    echo "subagent: true"
    echo "mainAgent: false"
    echo "---"
    echo
    echo "<!-- $MARKER from agents/$name.md. Edit the source, then re-run the script. -->"
    awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {in_fm=0; next} !in_fm' "$src"
  } > "$OUT/$name.md"
  echo "agent    $name"
done
