#!/usr/bin/env bash
# Fan agents/, rules/, commands/ and hooks out into Antigravity (~/.gemini/config).
#
#   agents/*.md    -> GENERATED into ~/.gemini/config/agents/<name>.md with
#                     `enable_write_tools` and Antigravity tool names mapped
#                     from Claude's `tools:`.
#   rules/*.md     -> GENERATED into ~/.gemini/config/rules/<name>.md converting
#                     Claude's `paths:` list into `trigger: glob` + `globs:`.
#   commands/*.md  -> GENERATED into ~/.gemini/config/command-skills/<name>/SKILL.md
#                     (with `disable-model-invocation: true`) and registered via
#                     ~/.gemini/config/skills.json. Workflows (`global_workflows`)
#                     are deprecated in Antigravity; skills provide `/<name>`
#                     slash commands natively while keeping `skills/` clean.
#   hooks.json     -> GENERATED at ~/.gemini/config/hooks.json, delegating
#                     PreToolUse and PostToolUse to antigravity/hooks-adapter.sh.
#
# Re-run after adding or editing an agent, rule, or command.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CFG="${AGY_CONFIG_DIR:-$HOME/.gemini/config}"
MARKER="Generated by agents-hub/antigravity/sync-antigravity.sh"

map_tool() {
  case "$1" in
    Read|Grep|Glob) echo view_file ;;
    Bash)           echo run_command ;;
    Edit)           echo replace_file_content ;;
    Write)          echo write_to_file ;;
  esac
}

mkdir -p "$CFG/agents" "$CFG/rules" "$CFG/command-skills"
[ -L "$CFG/global_workflows" ] && rm -f "$CFG/global_workflows"

# 1. Agents
{ grep -l "$MARKER" "$CFG/agents/"*.md 2>/dev/null || true; } | xargs rm -f

for src in "$REPO"/agents/*.md; do
  name=$(basename "$src" .md)
  frontmatter=$(awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {exit} in_fm' "$src")
  description=$(echo "$frontmatter" | grep -m1 '^description:' || true)
  tools=$(echo "$frontmatter" | sed -n 's/^tools:[[:space:]]*//p')
  [ -z "$tools" ] && tools="Read, Grep, Glob, Bash, Edit, Write"

  enable_write="false"
  if echo "$tools" | grep -qwE 'Edit|Write|Bash'; then
    enable_write="true"
  fi

  {
    echo "---"
    echo "name: $name"
    echo "$description"
    echo "enable_write_tools: $enable_write"
    echo "tools:"
    for t in $(echo "$tools" | tr ',' ' '); do map_tool "$t"; done | awk '!seen[$0]++ {print "  - " $0}'
    echo "subagent: true"
    echo "mainAgent: false"
    echo "---"
    echo
    echo "<!-- $MARKER from agents/$name.md. Edit the source, then re-run the script. -->"
    awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {in_fm=0; next} !in_fm' "$src"
  } > "$CFG/agents/$name.md"
  echo "agent    $name"
done

# 2. Path-scoped rules (paths: -> trigger: glob + globs:)
{ grep -l "$MARKER" "$CFG/rules/"*.md 2>/dev/null || true; } | xargs rm -f

for src in "$REPO"/rules/*.md; do
  name=$(basename "$src" .md)
  frontmatter=$(awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {exit} in_fm' "$src")
  body=$(awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {in_fm=0; next} !in_fm' "$src")
  globs=$(echo "$frontmatter" | sed -n 's/^[[:space:]]*-[[:space:]]*"\([^"]*\)".*/\1/p' | paste -sd ',' - | sed 's/,/, /g')
  heading=$(echo "$body" | sed -n 's/^#[[:space:]]*//p' | head -n 1)
  [ -z "$heading" ] && heading="$name"

  {
    echo "---"
    echo "trigger: glob"
    echo "globs: \"$globs\""
    echo "description: \"$heading coding standards and tooling rules\""
    echo "---"
    echo
    echo "<!-- $MARKER from rules/$name.md. Edit the source, then re-run the script. -->"
    echo "$body"
  } > "$CFG/rules/$name.md"
  echo "rule     $name"
done

# 3. Commands -> command-skills/<name>/SKILL.md + skills.json
{ grep -rl "$MARKER" "$CFG/command-skills/" 2>/dev/null || true; } | while read -r f; do
  rm -rf "$(dirname "$f")"
done

for src in "$REPO"/commands/*.md; do
  name=$(basename "$src" .md)
  frontmatter=$(awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {exit} in_fm' "$src")
  description=$(echo "$frontmatter" | sed -n 's/^description:[[:space:]]*//p' | head -n 1)
  mkdir -p "$CFG/command-skills/$name"
  {
    echo "---"
    echo "name: $name"
    echo "description: >-"
    echo "  $description"
    echo "disable-model-invocation: true"
    echo "---"
    echo
    echo "<!-- $MARKER from commands/$name.md. Edit the source, then re-run the script. -->"
    awk 'NR==1 && /^---$/ {in_fm=1; next} in_fm && /^---$/ {in_fm=0; next} !in_fm' "$src"
  } > "$CFG/command-skills/$name/SKILL.md"
  echo "command  $name"
done

cat > "$CFG/skills.json" <<'EOF'
{
  "entries": [
    {
      "path": "~/.gemini/config/command-skills"
    }
  ]
}
EOF
echo "config   skills.json"

# 4. Lifecycle hooks (hooks.json)
ADAPTER="$REPO/antigravity/hooks-adapter.sh"
cat > "$CFG/hooks.json" <<EOF
{
  "agents-hub-guards": {
    "PreToolUse": [
      {
        "matcher": "run_command|write_to_file|replace_file_content|multi_replace_file_content|write_file|edit_file",
        "hooks": [
          {
            "type": "command",
            "command": "bash \"$ADAPTER\" PreToolUse",
            "timeout": 15
          }
        ]
      }
    ],
    "PostToolUse": [
      {
        "matcher": "write_to_file|replace_file_content|multi_replace_file_content|write_file|edit_file",
        "hooks": [
          {
            "type": "command",
            "command": "bash \"$ADAPTER\" PostToolUse",
            "timeout": 15
          }
        ]
      }
    ]
  }
}
EOF
echo "config   hooks.json"
